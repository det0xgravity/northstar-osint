def hide_raw_css(root):
    """Hide raw tool folders and case files from the file explorer (they stay linkable)."""
    sel = []
    for case in sorted(os.listdir(root)):
        cp = os.path.join(root, case)
        if not is_case(cp):
            continue
        for n in sorted(os.listdir(cp)):
            p = os.path.join(cp, n)
            dp = f"{case}/{n}".replace('"', '\\"')
            if os.path.isdir(p) and n not in NOTE_DIRS and n != "subject" and not n.startswith("."):
                sel.append(f'.nav-folder:has(> .nav-folder-title[data-path="{dp}"])')
            elif os.path.isfile(p) and n in CASE_FILES - {"Case.md", "Results.md", "notes.md"}:
                sel.append(f'.nav-file:has(> .nav-file-title[data-path="{dp}"])')
    css = ("/* northstar: hides raw tool output from the file list (regenerated). Disable this snippet in\n"
           "   Settings → Appearance → CSS snippets to browse it. Links and embeds still work. */\n")
    if sel:
        css += ",\n".join(sel) + " { display: none; }\n"
    write(os.path.join(root, ".obsidian", "snippets", "northstar-hide-raw.css"), css)


def merge_json(path, defaults, managed):
    conf = read_json(path, None)
    if not isinstance(conf, dict):
        conf = {}
    for k, v in defaults.items():
        conf.setdefault(k, v)
    conf.update(managed)
    write(path, json.dumps(conf, indent=2) + "\n")


def refresh_shared(root):
    home(root)
    hide_raw_css(root)


def cmd_setup(data_dir):
    root = cases_root(data_dir)
    os.makedirs(root, mode=0o700, exist_ok=True)
    obs = os.path.join(root, ".obsidian")
    for name, defaults in OBSIDIAN_DEFAULTS.items():
        merge_json(os.path.join(obs, name), defaults, MANAGED.get(name, {}))
    ap = os.path.join(obs, "appearance.json")
    conf = read_json(ap, {}) or {}
    snippets = conf.get("enabledCssSnippets") or []
    for s in ("northstar", "northstar-hide-raw"):
        if s not in snippets and s not in conf.get("northstarDisabledSnippets", []):
            snippets.append(s)
    conf["enabledCssSnippets"] = snippets
    write(ap, json.dumps(conf, indent=2) + "\n")
    write(os.path.join(obs, "snippets", "northstar.css"), THEME_CSS)
    for name, text in TEMPLATES.items():
        p = os.path.join(root, "_templates", f"{name}.md")
        # refresh our own templates; a template you've edited is left alone
        if not os.path.exists(p) or open(p, encoding="utf-8").read().endswith(MARK + "\n"):
            write(p, text + "\n" + MARK + "\n")
    made = 0
    for case in sorted(os.listdir(root)):
        cp = os.path.join(root, case)
        if not is_case(cp):
            continue
        existing = set(os.listdir(os.path.join(cp, "Results"))) if os.path.isdir(os.path.join(cp, "Results")) else set()
        for rd in result_dirs(cp):
            if note_name(describe(cp, rd)) not in existing:
                result_note(cp, rd)
                made += 1
        cmd_case(cp, quiet=True)
    refresh_shared(root)
    print(f"Vault ready: {root}" + (f" ({made} result notes written)" if made else ""))
    return 0


def cmd_register(data_dir, config_json):
    """Obsidian keeps its vault list in obsidian.json; add ours so links open it."""
    root = os.path.realpath(cases_root(data_dir))
    conf = {}
    if os.path.exists(config_json):
        conf = read_json(config_json, None)
        if not isinstance(conf, dict):
            print("obsidian.json isn't valid JSON: left alone.")
            return 1
    vaults = conf.setdefault("vaults", {})
    if any(os.path.realpath(v.get("path", "")) == root for v in vaults.values()):
        print("Vault already registered.")
        return 0
    vid = hashlib.sha256(root.encode()).hexdigest()[:16]
    vaults[vid] = {"path": root, "ts": int(time.time() * 1000), "open": True}
    os.makedirs(os.path.dirname(config_json), mode=0o700, exist_ok=True)
    with open(config_json, "w", encoding="utf-8") as fh:
        json.dump(conf, fh)
    print(f"Vault registered with Obsidian: {root}")
    return 0


def cmd_result(case_dir, result_dir):
    rel = os.path.relpath(os.path.abspath(result_dir), os.path.abspath(case_dir))
    if rel.startswith("..") or not os.path.isdir(result_dir):
        return 0
    path, _ = result_note(case_dir, result_dir)
    cmd_case(case_dir, quiet=True)
    refresh_shared(os.path.dirname(os.path.abspath(case_dir)))
    print(path)
    return 0


def cmd_refresh(case_dir):
    n = 0
    for rd in result_dirs(case_dir):
        result_note(case_dir, rd)
        n += 1
    cmd_case(case_dir, quiet=True)
    refresh_shared(os.path.dirname(os.path.abspath(case_dir)))
    print(f"{n} result notes rebuilt.")
    return 0


def cmd_new(case_dir, kind, title):
    kind = kind.lower()
    if kind not in TYPES:
        print(f"Type must be one of: {', '.join(TYPES)}", file=sys.stderr)
        return 2
    root = os.path.dirname(os.path.abspath(case_dir))
    tpl_path = os.path.join(root, "_templates", f"{kind.capitalize()}.md")
    tpl = open(tpl_path, encoding="utf-8").read() if os.path.exists(tpl_path) else TEMPLATES[kind.capitalize()]
    tpl = tpl.replace(MARK, "").rstrip() + "\n"
    safe = re.sub(r'[\\/:*?"<>|#^\[\]]', "-", title).strip() or "Untitled"
    path = os.path.join(case_dir, TYPES[kind], f"{safe}.md")
    text = (tpl.replace("{{title}}", title).replace("{{date:YYYY-MM-DD}}", utc("%Y-%m-%d"))
            .replace("{{date}}", utc("%Y-%m-%d")).replace("{{time}}", utc("%H:%M")))
    write_if_missing(path, text)
    cmd_case(case_dir, quiet=True)
    print(path)
    return 0


def cmd_uri(path):
    print("obsidian://open?path=" + urllib.parse.quote(os.path.abspath(path), safe=""))
    return 0


def main(argv):
    cmds = {"setup": (cmd_setup, 1), "register": (cmd_register, 2), "case": (cmd_case, 1),
            "result": (cmd_result, 2), "refresh": (cmd_refresh, 1), "new": (cmd_new, 3), "uri": (cmd_uri, 1)}
    if len(argv) < 2 or argv[1] not in cmds or len(argv) - 2 != cmds[argv[1]][1]:
        print(__doc__)
        return 2
    return cmds[argv[1]][0](*argv[2:])


if __name__ == "__main__":
    sys.exit(main(sys.argv))

def set_props(path, updates):
    """Change properties in place, keeping everything else in the note."""
    text = read_text(path, 8 * 1024 * 1024)
    entries, body = split_front(text)
    if not entries and not text.startswith("---\n"):
        body = text
    keys = {k for k, _ in entries}
    new = []
    for k, lines in entries:
        new.append([f"{k}: {updates[k]}"] if k in updates else lines)
    new += [[f"{k}: {v}"] for k, v in updates.items() if k not in keys]
    write(path, "---\n" + "\n".join("\n".join(l) for l in new) + "\n---\n" + body)


def cmd_discount(case_dir, name, reason):
    path = os.path.join(case_dir, "Findings", name + ".md")
    if not os.path.isfile(path) or not reason.strip():
        print("No such finding, or no reason given.", file=sys.stderr)
        return 1
    with case_lock(case_dir):
        set_props(path, {"status": "discounted", "reportable": "false", "discount_reason": json.dumps(reason.strip()),
                         "discounted_utc": json.dumps(utc("%Y-%m-%dT%H:%M:%SZ"))})
        update_case(case_dir)
    print(f"Finding '{name}' discounted.")
    return 0



# --- small helpers ----------------------------------------------------------------
def utc(fmt="%Y-%m-%d %H:%M UTC"):
    return datetime.datetime.now(datetime.timezone.utc).strftime(fmt)


def write(path, text):
    """Case notes are readable only by you, like the rest of the case."""
    os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(path, 0o600)


def write_if_missing(path, text):
    if os.path.exists(path):
        return False
    write(path, text)
    return True


def read_json(path, default=None):
    try:
        return json.load(open(path, encoding="utf-8"))
    except (OSError, ValueError):
        return default


def cell(v, limit=120):
    """Table cell text from untrusted content: no HTML, links, embeds or line breaks."""
    s = re.sub(r"\s+", " ", str(v if v is not None else "")).strip()
    if len(s) > limit:
        s = s[:limit - 1] + "…"
    for a, b in (("\\", "\\\\"), ("|", "\\|"), ("<", "&lt;"), (">", "&gt;"), ("[", "\\["), ("]", "\\]"),
                 ("`", "'"), ("*", "\\*"), ("_", "\\_")):
        s = s.replace(a, b)
    return s


def fence(text):
    """A code block that untrusted text can't break out of."""
    ticks = "`" * max(3, max((len(m) for m in re.findall(r"`+", text)), default=0) + 1)
    return f"{ticks}text\n{text.rstrip()}\n{ticks}"


def wlink(vault_path, label=None, table=False):
    """[[path|label]]; inside a table the pipe must be escaped or it splits the cell."""
    label = label or os.path.basename(vault_path)
    return f"[[{vault_path}{chr(92) + '|' if table else '|'}{cell(label, 80)}]]"


def code(v, limit=200):
    """Inline code: only backticks and line breaks need care."""
    return "`" + re.sub(r"\s+", " ", str(v)).replace("`", "'")[:limit] + "`"


def cases_root(data_dir):
    return os.path.join(data_dir, "Cases")


def vpath(case_dir, *parts):
    """Vault-relative path (case/…) for wikilinks."""
    return "/".join([os.path.basename(os.path.abspath(case_dir))] + [p for p in parts if p])



# --- findings and the report --------------------------------------------------------------
REPORTABLE = ("corroborated", "confirmed")
SRC_GRADES = {"A": "always reliable", "B": "usually reliable", "C": "fairly reliable", "D": "not usually reliable",
              "E": "unreliable", "F": "reliability can't be judged"}
INFO_GRADES = {"1": "confirmed by other sources", "2": "probably true", "3": "possibly true", "4": "doubtful",
               "5": "improbable", "6": "truth can't be judged"}


def manifest_sha(folder):
    try:
        with open(os.path.join(folder, "manifest.sha256"), "rb") as fh:
            return hashlib.sha256(fh.read()).hexdigest()
    except OSError:
        return ""


def resolve_note(case_dir, link):
    """[[path|alias]] or a plain name → note file, searched in the case."""
    t = re.sub(r"^!?\[\[|\]\]$", "", str(link).strip()).split("|")[0].split("#")[0].strip()
    if not t:
        return ""
    root = os.path.dirname(os.path.abspath(case_dir))
    for cand in (os.path.join(root, t), os.path.join(case_dir, t), os.path.join(case_dir, "Results", os.path.basename(t))):
        for c in (cand, cand + ".md"):
            if os.path.isfile(c) and os.path.abspath(c).startswith(os.path.abspath(case_dir) + os.sep):
                return c
    return ""


def note_body(path):
    text = read_text(path, 4 * 1024 * 1024)
    if text.startswith("---\n") and "\n---" in text[4:]:
        text = text[4:].split("\n---", 1)[1].lstrip("-").lstrip("\n")
    return text


def findings(case_dir):
    """Every Finding note with the checks the report relies on."""
    out = []
    fdir = os.path.join(case_dir, "Findings")
    ex_rows = {r.get("exhibit_id"): r for r in exhibits(case_dir)}
    for n in sorted(os.listdir(fdir)) if os.path.isdir(fdir) else []:
        if not n.endswith(".md"):
            continue
        path = os.path.join(fdir, n)
        m = props(path)
        status = str(m.get("status") or "lead").strip().lower()
        f = {"name": n[:-3], "path": path, "props": m, "status": status, "reportable": m.get("reportable") is True,
             "src": str(m.get("source_grade") or "").strip().upper()[:1], "info": str(m.get("info_grade") or "").strip()[:1],
             "when": str(m.get("when_utc") or ""), "issues": [], "evidence": []}
        for ex in as_list(m.get("exhibits")):
            ex = str(ex).strip()
            row = ex_rows.get(ex)
            if not row:
                f["issues"].append(f"exhibit {ex} isn't in the exhibits register")
                continue
            now = manifest_sha(os.path.join(case_dir, row.get("folder", "")))
            ok = now == row.get("manifest_sha256")
            f["evidence"].append({"ref": ex, "folder": row.get("folder", ""), "sha": row.get("manifest_sha256", ""), "ok": ok,
                                  "desc": row.get("description", "")})
            if not ok:
                f["issues"].append(f"exhibit {ex} no longer matches its recorded fingerprint" if now else
                                   f"exhibit {ex}: its folder or manifest is missing")
        for link in as_list(m.get("results")):
            note = resolve_note(case_dir, link)
            if not note:
                f["issues"].append(f"result link {str(link)[:80]} doesn't resolve to a note in this case")
                continue
            rp = props(note)
            folder = str(rp.get("folder") or "")
            sha = manifest_sha(os.path.join(case_dir, folder)) if folder else ""
            f["evidence"].append({"ref": rp.get("exhibit") or os.path.basename(note)[:-3], "folder": folder, "sha": sha,
                                  "ok": bool(sha), "desc": f"{rp.get('tool', '')}: {rp.get('target', '')}"})
            if not sha:
                f["issues"].append(f"result {os.path.basename(note)[:-3]} isn't sealed")
            if str(rp.get("tool", "")).startswith("Face comparison"):
                f["issues"].append("cites a face comparison: report it as similarity for human review, never as identification")
        if status not in STATUSES:
            f["issues"].append(f"status '{status}' isn't one of {', '.join(STATUSES)}")
        if f["reportable"]:
            if status not in REPORTABLE:
                f["issues"].append(f"marked reportable but its status is '{status}' (only corroborated or confirmed findings are reported)")
            if not any(e["ok"] for e in f["evidence"]):
                f["issues"].append("cites no sealed exhibit or sealed result")
            if f["src"] not in SRC_GRADES or f["info"] not in INFO_GRADES:
                f["issues"].append("source_grade (A-F) and info_grade (1-6) aren't both set")
        if status == "discounted" and not str(m.get("discount_reason") or "").strip():
            f["issues"].append("discounted without a discount_reason")
        seen, ev = set(), []
        for e in f["evidence"]:                       # one row per folder (an exhibit and its result note agree)
            if e["folder"] not in seen:
                seen.add(e["folder"])
                ev.append(e)
        f["evidence"] = ev
        f["included"] = f["reportable"] and status in REPORTABLE
        out.append(f)
    return out


def verify_files(case_dir, folder):
    """Every file still matches the folder's manifest (ns_evidence verify); None if it can't be checked."""
    exe = shutil.which("ns_evidence")
    if not exe or not folder:
        return None
    try:
        p = subprocess.run([exe, "verify", os.path.join(case_dir, folder)], capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.SubprocessError):
        return None
    return " 0 CHANGED, 0 MISSING" in p.stdout


def findings_hash(fs):
    h = hashlib.sha256()
    for f in sorted((x for x in fs if x["included"]), key=lambda x: x["name"]):
        h.update(f["name"].encode() + b"\0")
        with open(f["path"], "rb") as fh:
            h.update(fh.read() + b"\0")
    return h.hexdigest()


def deleted_findings(case_dir, fs):
    """Finding notes that existed before and are gone now (findings should be discounted, not deleted)."""
    reg = os.path.join(case_dir, ".northstar", "findings-seen.json")
    seen = set(read_json(reg, []) or [])
    now = {f["name"] for f in fs}
    gone = sorted(seen - now)
    write(reg, json.dumps(sorted(seen | now), indent=1))
    return gone


def last_review(case_dir):
    """The latest supervisor review from the hash-chained notes: (line text, findings hash)."""
    text = read_text(os.path.join(case_dir, "notes.md"), 16 * 1024 * 1024)
    revs = [l for l in text.splitlines() if "[REVIEW]" in l]
    if not revs:
        return "", ""
    m = re.search(r"findings sha256 ([0-9a-f]{64})", revs[-1])
    return re.sub(r" `h:[0-9a-f]{64}`$", "", revs[-1]).lstrip("- "), (m.group(1) if m else "")


PLACEHOLDERS = ("What is known so far, in a few lines.",
                "Hypotheses, what supports or contradicts them, and what would settle them.", "- [ ]", "- [ ] ",
                "What the source shows, in plain terms, with the date and where it was seen. No interpretation here.",
                "What you conclude from it, and why. Alternative explanations you considered.", "- ")


def plain(md, depth=1):
    """Obsidian-only syntax → text pandoc renders: links to labels, embeds to placeholders, no guidance
    callout or untouched template prompts; headings nested `depth` levels under the report's own."""
    md = "\n".join(l for l in md.splitlines() if l.strip() not in PLACEHOLDERS or not l.strip())
    md = re.sub(r"(?m)^#+ [^\n]*\n(?=\s*(?:#+ |\Z))", "", md + "\n")           # headings left with nothing under them
    md = re.sub(r"(?ms)^> \[!finding\] How this note works\n(?:>.*\n?)*", "", md)
    md = re.sub(r"!\[\[([^\]|]+)(\|[^\]]*)?\]\]", lambda m: f"(image: {os.path.basename(m.group(1))})", md)
    md = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", md)
    md = re.sub(r"\[\[([^\]]+)\]\]", lambda m: os.path.basename(m.group(1)), md)
    md = re.sub(r"(?m)^> \[!(\w+)\][+-]? ?", r"> **\1:** ", md)
    md = re.sub(r"(?m)^(#+) ", lambda m: "#" * min(6, len(m.group(1)) + depth) + " ", md)
    return md.strip()


def report_sections(case_dir):
    """Markdown for the report: summary and analysis from Case.md, findings, nil searches,
    unused material, review status and warnings. Returns (markdown, frozen copy, hash, warnings, included)."""
    fs = findings(case_dir)
    for f in fs:                                       # report time: re-check the evidence files themselves
        if not f["included"]:
            continue
        for e in f["evidence"]:
            if e["ok"] and verify_files(case_dir, e["folder"]) is False:
                e["ok"] = False
                f["issues"].append(f"files in {e['folder']} no longer match its manifest")
    fhash = findings_hash(fs)
    gone = deleted_findings(case_dir, fs)
    warnings = [f"{f['name']}: {i}" for f in fs if f["reportable"] or f["status"] == "discounted" for i in f["issues"]]
    warnings += [f"finding note deleted: {g} (discount findings instead of deleting them)" for g in gone]
    review, rhash = last_review(case_dir)
    if not review:
        warnings.append("no supervisor review recorded (Case → Record a supervisor review)")
    elif rhash != fhash:
        warnings.append("findings have changed since the last review")
    r = []
    if warnings:
        r += ["## Report warnings", "", "Resolve these before the report is relied on:", ""] + [f"- {cell(w, 300)}" for w in warnings] + [""]
    case_md = read_text(os.path.join(case_dir, "Case.md"), 8 * 1024 * 1024)
    analyst = case_md.split(AUTO_END, 1)[1] if AUTO_END in case_md else ""
    r += ["## Summary and analysis", "", plain(analyst) or "*No summary written in Case.md.*", ""]
    inc = sorted((f for f in fs if f["included"]), key=lambda f: (f["when"] or "~", f["name"]))
    r += ["## Findings", ""]
    if not inc:
        r += ["*No findings marked reportable (status corroborated or confirmed, reportable: true).*", ""]
    for i, f in enumerate(inc, 1):
        g = (f"{f['src']}{f['info']} (source {SRC_GRADES.get(f['src'], '?')}, information {INFO_GRADES.get(f['info'], '?')})"
             if f["src"] or f["info"] else "not graded")
        r += [f"### F{i}. {f['name']}", "", f"- **Status:** {f['status']}", f"- **Grading:** {g}",
              f"- **When (UTC):** {cell(f['when'] or '—')}"]
        subj = as_list(f["props"].get("subjects"))
        if subj:
            r.append("- **Subjects:** " + ", ".join(cell(plain(str(s))) for s in subj))
        body = note_body(f["path"])
        r += ["", plain(body.split("\n", 1)[1] if body.startswith("# ") else body, depth=2), ""]
        if f["evidence"]:
            r += ["| Evidence | Folder | Fingerprint (SHA-256) | Check |", "|---|---|---|---|"]
            r += [f"| {cell(e['ref'])} | {cell(e['folder'])} | `{e['sha'] or '—'}` | {'matches' if e['ok'] else 'PROBLEM'} |"
                  for e in f["evidence"]]
            r.append("")
    nil = []
    for w, t, tg, n in results_index(case_dir):
        rp = props(os.path.join(case_dir, "Results", n))
        if rp.get("nil_return") is True:
            nil.append((w, t, tg, "no result (checked by the analyst)"))
        elif rp.get("no_output") is True and rp.get("nil_return") is not False:
            nil.append((w, t, tg, "no output saved (not yet checked)"))
    r += ["## Searches with no result", ""]
    r += (["| When (UTC) | Tool | Target | Outcome |", "|---|---|---|---|"]
          + [f"| {cell(w)} | {cell(t)} | {cell(tg)} | {o} |" for w, t, tg, o in nil] if nil else ["None recorded."]) + [""]
    unused = [f for f in fs if not f["included"]]
    r += ["## Unused material", "", "Findings recorded during the case and not relied on in this report:", ""]
    r += (["| Finding | Status | Reason |", "|---|---|---|"]
          + [f"| {cell(f['name'])} | {cell(f['status'])} | {cell(f['props'].get('discount_reason') or ('not marked reportable' if not f['reportable'] else 'status not corroborated or confirmed'), 200)} |"
             for f in unused] if unused else ["None."]) + [""]
    rv = re.sub(r"^\*\*([^*]+)\*\* \(([^)]*)\): \[REVIEW\] ", r"\1 (recorded by \2): ", review)
    r += ["## Review", "", (cell(rv, 600).replace("\\_", "_") if review else "No supervisor review recorded."),
          "", f"Findings fingerprint for this report (SHA-256 of the included finding notes): `{fhash}`", ""]
    frozen = [f"# Findings as used in the report\n\nFindings fingerprint: {fhash}\n"]
    for f in inc:
        with open(f["path"], encoding="utf-8", errors="replace") as fh:
            raw = fh.read()
        frozen.append(f"\n---\n## {f['name']}\nSHA-256 of the note: {hashlib.sha256(raw.encode('utf-8')).hexdigest()}\n\n{raw}")
    return "\n".join(r) + "\n", "".join(frozen), fhash, warnings, len(inc)


def cmd_report_sections(case_dir, out_dir):
    with case_lock(case_dir):
        md, frozen, fhash, warnings, n = report_sections(case_dir)
    os.makedirs(out_dir, mode=0o700, exist_ok=True)
    write(os.path.join(out_dir, "findings-section.md"), md)
    write(os.path.join(out_dir, "findings-frozen.md"), frozen)
    print(f"findings_sha256={fhash}\nincluded={n}\nwarnings={len(warnings)}")
    for w in warnings:
        print(f"warning={w}")
    return 0


def integrity(case_dir):
    """[(record, status, ok)] for the tamper-evident records, using northstar's own verifiers."""
    out = []
    def run(cmd):
        exe = shutil.which(cmd[0])
        if not exe:
            return None
        try:
            p = subprocess.run([exe] + cmd[1:], capture_output=True, text=True, timeout=120)
            return (p.stdout.strip().splitlines() or [""])[0], p.returncode == 0
        except (OSError, subprocess.SubprocessError):
            return None
    if os.path.exists(os.path.join(case_dir, "notes.md")):
        r = run(["ns_casework", "notes-verify", case_dir])
        if r:
            out.append(("Contemporaneous notes", r[0], r[1] and " 0 BROKEN" in r[0]))
    if os.path.exists(os.path.join(case_dir, "audit.log")):
        r = run(["ns_evidence", "audit-verify", os.path.join(case_dir, "audit.log")])
        if r:
            out.append(("Audit log", r[0], " 0 BROKEN" in r[0]))
    rows = exhibits(case_dir)
    if rows:
        bad = [x["exhibit_id"] for x in rows if manifest_sha(os.path.join(case_dir, x.get("folder", ""))) != x.get("manifest_sha256")]
        out.append(("Exhibits", f"{len(rows) - len(bad)} of {len(rows)} match their recorded fingerprints"
                    + (f"; CHANGED: {', '.join(bad[:10])}" if bad else ""), not bad))
    return out


def cmd_integrity(case_dir):
    res = integrity(case_dir)
    for name, status, ok in res:
        print(f"{'ok ' if ok else 'BAD'} {name}: {status}")
    return 0 if all(ok for _, _, ok in res) else 1



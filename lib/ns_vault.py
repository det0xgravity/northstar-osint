STAMP = re.compile(r"^(?P<target>.*?)_?(?P<d>\d{8})-(?P<t>\d{6})$")


def is_result(path):
    return any(os.path.exists(os.path.join(path, f)) for f in ("provenance.json", "manifest.sha256", "console.log",
                                                               ".ns-tools"))


def result_dirs(case_dir):
    """Result folders: <case>/<kind>/<target>_<YYYYmmdd-HHMMSS>/ (or deeper for country searches)."""
    found = []
    for kind in sorted(os.listdir(case_dir)):
        kp = os.path.join(case_dir, kind)
        if kind.startswith((".", "_")) or kind in NOTE_DIRS or not os.path.isdir(kp) or kind == "watch":
            continue
        for sub in sorted(os.listdir(kp)):
            sp = os.path.join(kp, sub)
            if os.path.isdir(sp) and (STAMP.match(sub) or is_result(sp)) and is_result(sp):
                found.append(sp)
    return found


def describe(case_dir, result_dir):
    rel = os.path.relpath(result_dir, case_dir)
    kind = rel.split(os.sep)[0]
    base = os.path.basename(result_dir)
    m = STAMP.match(base)
    target = (m.group("target") if m else base).replace("_", " ").strip() or "(no target)"
    when = (datetime.datetime.strptime(m.group("d") + m.group("t"), "%Y%m%d%H%M%S").strftime("%Y-%m-%d %H:%M:%S")
            if m else "")
    prov = read_json(os.path.join(result_dir, "provenance.json"), {}) or {}
    label = LABELS.get(kind) or ("Country search: " + kind.replace("-", " ").title())
    return {"rel": rel, "kind": kind, "label": label, "target": target, "when": when, "prov": prov}


def note_name(info):
    stamp = info["when"].replace(":", "") if info["when"] else "undated"        # 2026-10-26 150010
    safe = re.sub(r'[\\/:*?"<>|#^\[\]]', "-", f"{stamp} {info['label']} - {info['target']}")
    return re.sub(r"\s+", " ", safe)[:150].strip() + ".md"


def csv_table(path, rows=12, cols=6):
    """The first rows of a CSV, read as a stream (crawl output can be gigabytes)."""
    if os.path.islink(path):
        return "", 0
    try:
        csv.field_size_limit(1024 * 1024)
        with open(path, newline="", encoding="utf-8", errors="replace") as fh:
            reader = csv.reader(fh)
            head = next(reader, None)
            if not head:
                return "", 0
            head = head[:cols]
            body = list(itertools.islice(reader, rows))
            total = len(body) + sum(1 for _ in reader)
    except (OSError, csv.Error):
        return "", 0
    lines = ["| " + " | ".join(cell(h, 40) for h in head) + " |", "|" + "---|" * len(head)]
    for r in body:
        r = (r + [""] * len(head))[:len(head)]
        lines.append("| " + " | ".join(cell(c, 80) for c in r) + " |")
    return "\n".join(lines), total


SECRET_KEY = re.compile(r"pass|hash|secret|token|cookie|session|api.?key|credential|salt", re.I)


def json_table(path, limit=25):
    """Top-level fields only. Nested records are never expanded, and anything that
    looks like a credential is masked: notes must never carry secrets."""
    try:
        if os.path.islink(path) or os.path.getsize(path) > 20 * 1024 * 1024:
            return ""
    except OSError:
        return ""
    data = read_json(path)
    if not isinstance(data, dict):
        return ""
    rows = [(k, v) for k, v in data.items()
            if not isinstance(v, (dict, list)) or (isinstance(v, list) and len(v) < 8
                                                   and all(not isinstance(x, (dict, list)) for x in v))]
    if not rows:
        return ""
    lines = ["| Field | Value |", "|---|---|"]
    for k, v in rows[:limit]:
        if SECRET_KEY.search(str(k)):
            v = "(withheld)"
        elif isinstance(v, list):
            v = ", ".join(str(x) for x in v)
        lines.append(f"| {cell(k, 40)} | {cell(v)} |")
    return "\n".join(lines)


def found_accounts(console):
    """Username tools print found profiles as "[+] Site: URL"; holehe prints "[+] site.com"."""
    out = []
    for line in re.sub(r"\x1b\[[0-9;]*m", "", console).splitlines():
        m = re.match(r"^\s*\[\+\]\s*([^:]{1,60}):\s*(https?://\S+)", line)
        if m:
            out.append((m.group(1).strip(), m.group(2).strip()))
            continue
        m = re.match(r"^\s*\[\+\]\s*([a-z0-9.-]+\.[a-z]{2,})\s*$", line, re.I)
        if m:
            out.append((m.group(1), "(registered: no profile URL)"))
    return out


def result_note(case_dir, result_dir):
    info = describe(case_dir, result_dir)
    files, sizes = [], {}
    for root, dirs, names in os.walk(result_dir):          # os.walk doesn't follow symlinked folders
        dirs[:] = [d for d in sorted(dirs) if not d.startswith(".")]
        for n in sorted(names):
            full = os.path.join(root, n)
            if n.startswith(".") or os.path.islink(full):
                continue
            try:
                sizes[os.path.relpath(full, result_dir)] = os.lstat(full).st_size
            except OSError:
                continue
            files.append(os.path.relpath(full, result_dir))
    sealed = "manifest.sha256" in sizes
    fp = ""
    if sealed:
        h = hashlib.sha256()
        try:
            with open(os.path.join(result_dir, "manifest.sha256"), "rb") as fh:
                h.update(fh.read())
            fp = h.hexdigest()
        except OSError:
            sealed = False
    prov = info["prov"]
    vp = lambda f: vpath(case_dir, info["rel"].replace(os.sep, "/"), f.replace(os.sep, "/"))
    tools = ", ".join(f"{t} {v}".strip() for t, v in (prov.get("tools") or {}).items()) or "—"
    query = prov.get("query", "")
    exhibit = exhibit_for(case_dir, info["rel"])
    payload = [f for f in files if os.path.basename(f) not in NON_OUTPUT]
    managed = [("type", "result"), ("tool", json.dumps(info["label"])), ("target", json.dumps(info["target"])),
               ("captured_utc", json.dumps(prov.get("sealed_utc") or info["when"])),
               ("folder", json.dumps(info["rel"])), ("sealed", str(sealed).lower()),
               ("exhibit", json.dumps(exhibit.get("exhibit_id", ""))),
               ("no_output", str(not payload).lower())]
    out = [f"""# {cell(info['label'], 80)}: {cell(info['target'], 100)}

{AUTO_START}

> [!evidence] Provenance
> | | |
> |---|---|
> | Captured (UTC) | {cell(prov.get('sealed_utc') or info['when'])} |
> | Operator | {cell(prov.get('operator', '—'))} |
> | Tools | {cell(tools, 300)} |
> | Query / source | {cell(query or info['target'], 300)} |
> | Integrity | {'sealed · manifest SHA-256 ' + code(fp) if sealed else 'not sealed'} |
> | Exhibit | {cell(exhibit.get('exhibit_id') or 'not recorded as an exhibit (Evidence & exhibits → Record an exhibit)')} |
> | Folder | {code(info['rel'])} |"""]
    if not payload:
        out.append("> [!caution] No output saved\n> The tool saved no output files. If the search genuinely found nothing, "
                   "set **nil_return: true** in this note's properties so the report lists it under searches with no "
                   "result; if it failed, check the console output and run it again.")
    # A tool's own summary comes first
    if "summary.md" in files:
        text = read_text(os.path.join(result_dir, "summary.md"), 20000)
        if text.strip():
            out.append("## Summary\n\n" + fence(text))

    console = read_text(os.path.join(result_dir, "console.log"), 512 * 1024, tail=True) if "console.log" in files else ""
    accts = found_accounts(console)
    if accts:
        out.append(f"## Tool hits ({len(accts)}, unverified)\n\nWhat the tool reported. Each needs checking by hand before it's relied on "
                   "(record a checked account as an Account note, and a conclusion as a Finding).\n\n| Site | Profile |\n|---|---|\n"
                   + "\n".join(f"| {cell(s, 50)} | {cell(u, 200)} |" for s, u in accts[:200]))

    # Breach results: only ns_breach's summary.txt, which masks values; raw records stay in the folder
    breach = info["kind"] == "breach"
    for f in ([] if breach else [x for x in files if x.endswith(".csv")][:8]):
        table, n = csv_table(os.path.join(result_dir, f))
        if table:
            more = f" (first 12 of {n} rows)" if n > 12 else f" ({n} rows)"

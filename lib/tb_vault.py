def link_canvas(case_dir, agg):
    """A JSON Canvas (Obsidian core plugin) of people, accounts and selectors seen by two or more tools."""
    name = os.path.basename(os.path.abspath(case_dir))
    nodes, edges = [], []
    def nid(*parts):
        return hashlib.sha256("|".join(parts).encode()).hexdigest()[:16]
    cols = [("People", [vpath(case_dir, "People", n) + ".md" for n in notes_in(case_dir, "People")], "file"),
            ("Accounts", [vpath(case_dir, "Accounts", n) + ".md" for n in notes_in(case_dir, "Accounts")], "file"),
            ("Selectors", [f"{k}: {v}" for (k, v), a in sorted(agg.items(), key=lambda x: -len(x[1]["tools"]))
                           if len(a["tools"]) >= 2 and k != "url"][:60], "text")]
    acct_users = {}
    for x, (title, items, typ) in enumerate(cols):
        nodes.append({"id": nid("col", title), "type": "text", "text": f"## {title}", "x": x * 420, "y": -120,
                      "width": 360, "height": 60, "color": "5"})
        for y, item in enumerate(items):
            node = {"id": nid(title, item), "x": x * 420, "y": y * 140, "width": 360, "height": 110}
            if typ == "file":
                node.update({"type": "file", "file": item})
            else:
                node.update({"type": "text", "text": cell(item, 140)})
            nodes.append(node)
            if title == "Accounts":
                p = props(os.path.join(os.path.dirname(case_dir), item))
                acct_users[str(p.get("username") or "").lower()] = node["id"]
                owner = str(p.get("owner") or "")
                o = re.sub(r"^\[\[|\]\]$", "", owner).split("|")[0].strip()
                if o:
                    target = vpath(case_dir, "People", os.path.basename(o)) + ".md"
                    if target in cols[0][1]:
                        edges.append({"id": nid("e", item, target), "fromNode": node["id"], "toNode": nid("People", target),
                                      "label": "owned by"})
    for item in cols[2][1]:
        k, v = item.split(": ", 1)
        if k == "username" and v in acct_users:
            edges.append({"id": nid("e", item), "fromNode": nid("Selectors", item), "toNode": acct_users[v], "label": "username"})
    return {"nodes": nodes, "edges": edges}


def write_canvas(case_dir, agg):
    """Rewrite the chart only while it's as True Bearing left it; once edited, write a separate generated copy."""
    data = json.dumps(link_canvas(case_dir, agg), indent=1)
    path = os.path.join(case_dir, "Link chart.canvas")
    stamp = os.path.join(case_dir, ".truebearing", "canvas.sha256")
    last = read_text(stamp, 200).strip()
    if os.path.exists(path) and hashlib.sha256(read_text(path, 16 * 1024 * 1024).encode()).hexdigest() != last:
        path = os.path.join(case_dir, "Link chart (generated).canvas")
    else:
        write(stamp, hashlib.sha256(data.encode()).hexdigest())
    write(path, data)



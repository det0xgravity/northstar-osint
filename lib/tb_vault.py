def selectors_page(case_dir, agg):
    name = os.path.basename(os.path.abspath(case_dir))
    done = searched(case_dir)
    out = [f"---\ntype: index\ntags: [selectors]\n---\n# Selectors: {cell(name)}\n\n{MARK}\n",
           "> [!info] How to read this\n> Identifiers the tools reported in this case, collected from their result files. "
           "**Seen by** counts how many different tools reported the same value: the more, the stronger the link, but "
           "each still needs checking by hand. **Next** lists searches that would take it further; ✓ marks one already run "
           "on that value. Candidate usernames generated by the variants tool are not included."]
    for kind, title in SEL_TYPES:
        rows = sorted(((v, a) for (k, v), a in agg.items() if k == kind), key=lambda x: (-len(x[1]["tools"]), x[0]))
        if not rows:
            continue
        lines = [f"## {title} ({len(rows)})\n", "| Value | Seen by | First seen | In | Next |", "|---|---|---|---|---|"]
        for v, a in rows[:400]:
            nxt = " · ".join(("✓ " if (lbl, v) in done else "") + cell(menu) for menu, lbl in PIVOTS.get(kind, []))
            notes = " ".join(wlink(vpath(case_dir, "Results", n[:-3]), f"{i + 1}", True)
                             for i, n in enumerate(sorted(a["notes"])[:6]) if n)
            seen_by = (f"{len(a['tools'])} ({cell(', '.join(sorted(a['tools'])), 120)})" if a["tools"]
                       else "searched, not yet seen")
            lines.append(f"| {code(v, 120)} | {seen_by} | "
                         f"{cell(a['first'][:16])} | {notes} | {nxt} |")
        if len(rows) > 400:
            lines.append(f"\n{len(rows) - 400} more not shown.")
        out.append("\n".join(lines))
    if len(out) == 2:
        out.append("No selectors yet: they appear as searches finish.")
    return "\n\n".join(out) + "\n"


def accounts_from_hits(agg):
    """Profile URLs from tool hits, merged by platform and username."""
    acc = {}
    for (k, v), a in agg.items():
        if k != "url":
            continue
        plat, user = platform_of(v), user_of(v).lower()
        if not plat:
            continue
        key = (plat, user or v)
        e = acc.setdefault(key, {"platform": plat, "username": user, "urls": set(), "tools": set(), "notes": set(), "first": ""})
        e["urls"].add(v)
        e["tools"] |= a["tools"]
        e["notes"] |= a["notes"]
        if a["first"] and (not e["first"] or a["first"] < e["first"]):
            e["first"] = a["first"]
    return acc



def all_selectors(case_dir):
    """{(type, value): {"tools": set, "notes": set, "first": when}} across the case."""
    agg = {}
    d = os.path.join(case_dir, ".truebearing", "selectors")
    for n in os.listdir(d) if os.path.isdir(d) else []:
        rec = read_json(os.path.join(d, n), {}) or {}
        if not os.path.isdir(os.path.join(case_dir, rec.get("folder", "\0"))):
            continue                                          # result folder gone
        for s in rec.get("selectors", []):
            a = agg.setdefault((s["type"], s["value"]), {"tools": set(), "notes": set(), "first": ""})
            tool = s.get("tool") or rec.get("tool", "")
            if tool != SEARCHED:
                a["tools"].add(tool)
            a["notes"].add(rec.get("note", ""))
            w = rec.get("when", "")
            if w and (not a["first"] or w < a["first"]):
                a["first"] = w
    return agg


def searched(case_dir):
    """{(tool label, normalised target)} for pivot 'done' marks."""

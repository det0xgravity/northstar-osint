B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
BECH32 = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"


def bech32_ok(addr):
    """BIP 173/350: bech32 (witness v0) or bech32m (v1+) checksum."""
    hrp, _, data = addr.lower().rpartition("1")
    if hrp != "bc" or len(data) < 7 or any(c not in BECH32 for c in data):
        return False
    vals = [BECH32.index(c) for c in data]
    chk = 1
    for v in [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp] + vals:
        top = chk >> 25
        chk = (chk & 0x1ffffff) << 5 ^ v
        for i, g in enumerate((0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3)):
            chk ^= g if (top >> i) & 1 else 0
    return chk == (1 if vals[0] == 0 else 0x2bc830a3)


def base58check_ok(addr):
    n = 0
    for c in addr:
        n = n * 58 + B58.index(c)
    raw = n.to_bytes(25, "big") if n.bit_length() <= 200 else b""
    return len(raw) == 25 and raw[0] in (0, 5) and hashlib.sha256(hashlib.sha256(raw[:21]).digest()).digest()[:4] == raw[21:]


def crypto_ok(v):
    """A real address, not just the right shape: Bitcoin checksums are verified (a random string
    of the right shape fails 1 time in 4 billion); Ethereum-style 0x addresses can only be checked
    for shape here (EIP-55 needs Keccak-256, which Python doesn't ship)."""
    if v.startswith("0x"):
        return len(v) == 42 and v[2:] not in ("0" * 40, "f" * 40)
    if v.lower().startswith("bc1"):
        return (v == v.lower() or v == v.upper()) and bech32_ok(v)
    try:
        return base58check_ok(v)
    except ValueError:
        return False


def norm(kind, v):
    v = str(v).strip().strip(".,;:()[]<>\"'")
    if kind == "url" and not re.fullmatch(r"https?://[^\s<>\"'\[\]|`{}\\^]{3,2000}", v):
        return ""                                           # not a plain profile link
    if kind in ("email", "domain", "onion", "url"):
        v = v.lower()
    if kind == "domain":
        v = v[4:] if v.startswith("www.") else v
        return v if RX["domain"].match(v) else ""
    if kind in ("username", "telegram"):
        v = v.lstrip("@").lower()
        return v if re.fullmatch(r"[\w.-]{2,64}", v) else ""
    if kind == "phone":
        d = re.sub(r"[^\d+]", "", v)
        return d if 8 <= len(d.lstrip("+")) <= 15 else ""
    if kind == "crypto":
        v = v.lower() if v.lower().startswith(("bc1", "0x")) else v
        return v if crypto_ok(v) else ""
    if kind == "coordinates":
        try:
            lat, lon = (float(x) for x in v.split(","))
        except ValueError:
            return ""
        return f"{lat:.4f},{lon:.4f}" if -90 <= lat <= 90 and -180 <= lon <= 180 and (lat or lon) else ""
    return v


def platform_of(url):
    host = urllib.parse.urlsplit(url).netloc.lower()
    host = host[4:] if host.startswith("www.") else host
    return host.split(":")[0]


def user_of(url):
    path = [p for p in urllib.parse.urlsplit(url).path.split("/") if p and p not in ("user", "u", "users", "in", "profile", "@")]
    return path[-1].lstrip("@") if path else ""


def extract(case_dir, result_dir, info, console, files):
    """Typed selectors from known per-tool files (never whole captured pages)."""
    found = []
    def add(kind, value, src, tool=""):
        v = norm(kind, value)
        if v:
            found.append({"type": kind, "value": v, "source": src, "tool": tool or info["label"]})
    t = TARGET_TYPE.get(info["kind"])
    if t:
        add(t, info["target"].replace(" ", ""), "search target", SEARCHED)
    for site, url, tool in found_accounts(console, info["label"]):
        if url.startswith("http") and norm("url", url):
            add("url", url, "tool hit", tool)
            u = user_of(url)
            if u:
                add("username", u, f"tool hit ({platform_of(url)})", tool)
        else:
            add("domain", site, "registered on (tool hit)", tool)
    def scan(name, kinds, limit=256 * 1024):
        text = read_text(os.path.join(result_dir, name), limit)
        for k in kinds:
            for m in RX[k].finditer(text):
                add(k, m.group(0), name)
    base = {os.path.basename(f): f for f in files}
    if info["kind"] == "domain":
        for line in read_text(os.path.join(result_dir, base.get("subdomains.txt", "-")), 512 * 1024).splitlines()[:2000]:
            add("domain", line, "subdomains.txt")
        for n in ("rdap.txt", "dns.txt"):
            if n in base:
                scan(base[n], ("email", "ip", "phone"))
    if info["kind"] == "email-headers" and "headers.txt" in base:
        scan(base["headers.txt"], ("email", "ip"))
    if info["kind"] in ("breach", "email", "ghunt") and "summary.txt" in base:
        scan(base["summary.txt"], ("email",))
    if "onion_addresses.txt" in base:
        scan(base["onion_addresses.txt"], ("onion",))
    # Crypto addresses are checksum-verified, so free text is safe to read for them
    for n in ("page.txt", "posts.csv", "messages.csv", "links.txt", "summary.txt"):
        if n in base:
            scan(base[n], ("crypto",))
    for n in ("lookup.json", "user.json", "chat.json"):
        d = read_json(os.path.join(result_dir, base[n]), {}) if n in base else {}
        if isinstance(d, dict):
            if d.get("username"):
                add("telegram", d["username"], n)
            for u in d.get("usernames") or []:
                add("telegram", u, n)
            if d.get("id"):
                add("telegram", str(d["id"]), n)
            if d.get("phone"):
                add("phone", "+" + str(d["phone"]).lstrip("+"), n)
